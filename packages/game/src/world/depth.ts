  floor: -110,
  /** 地面の絵（GroundView）。 */
  ground: -100,
  /** 出口の帯・矢印。 */
  exit: -60,
  /** 場の物の下の光（F で使えるとき・転移の石）。 */
  propGlow: -55,
  /** 場の物（施設・宝箱・転移の石・隠し星）。 */
  prop: -50,
  /** 施設・転移の石・出口の名前（場の物の絵より手前、体より奥）。 */
  regionLabel: -40,
  /** 足元の影（敵・ドロップ・プレイヤー）を描く Graphics。 */
